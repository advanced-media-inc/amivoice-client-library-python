def bool_string(value: bool) -> str:
    """Bool 値を低レベルライブラリが受け取る ``"true"`` / ``"false"`` 文字列に変換する。

    Args:
        value: 変換する bool 値。

    Returns:
        ``"true"`` または ``"false"``。
    """
    return "true" if value else "false"
