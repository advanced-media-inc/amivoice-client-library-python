"""Hrp/Wrp トランスポートの型付きインタフェース定義。

高レベルクライアントが使用する低レベルライブラリのメソッドを Protocol として列挙する。
実 transport（``com.amivoice.hrp.Hrp`` / ``com.amivoice.wrp.Wrp``）は構造的部分型として
これらを満たし、テストでは同じインタフェースを持つ任意のオブジェクトを注入できる。

メソッド名は低レベルライブラリの命名（キャメルケース）にそのまま合わせる必要がある。
一方、引数は位置引数のみ（``/``）とすることで、引数名を snake_case にしても
実 transport 側のキャメルケース引数名と構造的部分型の互換性が保たれる。
"""

from typing import Protocol

from com.amivoice.hrp.HrpListener import HrpListener
from com.amivoice.wrp.WrpListener import WrpListener


class HrpTransport(Protocol):
    """``AmiVoiceClient.transcribe()`` が使用する HRP トランスポートのインタフェース。"""

    def setListener(self, listener: HrpListener | None, /) -> None: ...

    def setServerURL(self, server_url: str | None, /) -> None: ...

    def setProxyServerName(self, proxy_server_name: str | None, /) -> None: ...

    def setConnectTimeout(self, connect_timeout: int, /) -> None: ...

    def setReceiveTimeout(self, receive_timeout: int, /) -> None: ...

    def setGrammarFileNames(self, grammar_file_names: str | None, /) -> None: ...

    def setMode(self, mode: str | None, /) -> None: ...

    def setProfileId(self, profile_id: str | None, /) -> None: ...

    def setProfileWords(self, profile_words: str | None, /) -> None: ...

    def setSegmenterType(self, segmenter_type: str | None, /) -> None: ...

    def setSegmenterProperties(self, segmenter_properties: str | None, /) -> None: ...

    def setKeepFillerToken(self, keep_filler_token: str | None, /) -> None: ...

    def setResultUpdatedInterval(self, result_updated_interval: str | None, /) -> None: ...

    def setRecognitionTimeout(self, recognition_timeout: str | None, /) -> None: ...

    def setExtension(self, extension: str | None, /) -> None: ...

    def setServiceAuthorization(self, service_authorization: str | None, /) -> None: ...

    def setCodec(self, codec: str | None, /) -> None: ...

    def setResultType(self, result_type: str | None, /) -> None: ...

    def setResultEncoding(self, result_encoding: str | None, /) -> None: ...

    def setVoiceDetection(self, voice_detection: str | None, /) -> None: ...

    def setAcceptTopic(self, accept_topic: str | None, /) -> None: ...

    def setContentType(self, content_type: str | None, /) -> None: ...

    def setAccept(self, accept: str | None, /) -> None: ...

    def setDomainId(self, domain_id: str | None, /) -> None: ...

    def connect(self) -> bool: ...

    def disconnect(self) -> bool: ...

    def feedDataResume(self) -> bool: ...

    def feedData(self, data: bytes, data_offset: int, data_bytes: int, /) -> bool: ...

    def feedDataPause(self) -> bool: ...

    def getLastMessage(self) -> str: ...


